TARGET_GROUPS = [
    ["en", "tk", "prs", "ps", "be", "hu", "ky"],
    ["zh-Hans", "mn-Cyrl", "ur", "ru", "tr", "uz", "uk"],
]
APP_CODE = {"zh-Hans": "zh-CN", "mn-Cyrl": "mn"}


def translate_batch(client: httpx.Client, texts: list[str], targets: list[str]) -> list[dict[str, str]]:
    endpoint = os.environ["AZURE_TRANSLATOR_ENDPOINT"].rstrip("/")
    headers = {
        "Content-Type": "application/json",
        "Ocp-Apim-Subscription-Key": os.environ["AZURE_TRANSLATOR_KEY"],
        "X-ClientTraceId": str(uuid.uuid4()),
    }
    region = os.getenv("AZURE_TRANSLATOR_REGION", "").strip()
    if region:
        headers["Ocp-Apim-Subscription-Region"] = region
    params = [("api-version", "3.0"), ("from", "kk"), *[("to", target) for target in targets]]
    response = client.post(
        f"{endpoint}/translator/text/v3.0/translate",
        params=params,
        headers=headers,
        json=[{"Text": text} for text in texts],
    )
    response.raise_for_status()
    return [
        {APP_CODE.get(item["to"], item["to"]): item["text"] for item in result["translations"]}
        for result in response.json()
    ]


def main() -> None:
    source = [(category, text) for category, texts in CATEGORIES.items() for text in texts]
    assert len(source) == 300, f"Expected 300 entries, got {len(source)}"
    assert len({text.casefold() for _, text in source}) == 300, "Vocabulary entries must be unique"

    entries = [
        {"id": index + 1, "category": category, "kazakh": text, "translations": {"kk": text}}
        for index, (category, text) in enumerate(source)
    ]
    with httpx.Client(timeout=60.0) as client:
        for start in range(0, len(entries), 50):
            chunk = entries[start:start + 50]
            texts = [entry["kazakh"] for entry in chunk]
            for targets in TARGET_GROUPS:
                translated = translate_batch(client, texts, targets)
                for entry, result in zip(chunk, translated, strict=True):
                    entry["translations"].update(result)

    required = {"kk", "en", "tk", "prs", "ps", "be", "hu", "ky", "zh-CN", "mn", "ur", "ru", "tr", "uz", "uk"}
    assert all(set(entry["translations"]) == required for entry in entries)
    output = ROOT / "app" / "data" / "daily-vocabulary.json"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(entries, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    print(f"Generated {len(entries)} static entries at {output}")


if __name__ == "__main__":
    main()
